import { Router } from "express";
import { protect, requireAdmin } from "../middleware/auth.js";
import * as c from "../controllers/adminController.js";
const r = Router();
r.use(protect, requireAdmin);
r.get("/overview", c.overview);
r.get("/products", c.adminProducts);
r.post("/products", c.createProduct);
r.patch("/products/:id", c.updateProduct);
r.delete("/products/:id", c.deleteProduct);
r.get("/categories", c.categories);
r.post("/categories", c.createCategory);
r.patch("/categories/:id", c.updateCategory);
r.delete("/categories/:id", c.deleteCategory);
r.get("/customers", c.customers);
r.patch("/customers/:id/status", c.setCustomerStatus);
r.get("/orders", c.allOrders);
r.patch("/orders/:id/status", c.updateOrderStatus);
export default r;
